-- 3. FUNÇÕES E GATILHOS
-- =========================================================

-- ---------------------------------------------------------
-- Trigger 1 - RN18
-- Antes de inserir uma avaliação de episódio, verifica se o autor
-- já registrou aquele episódio como assistido.
-- Necessita consultar registro e avaliacao, logo não pode ser CHECK.
-- ---------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_avaliacao_exige_registro()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_usuario INTEGER;
BEGIN
    SELECT id_usuario
      INTO v_usuario
      FROM avaliacao
     WHERE id_avaliacao = NEW.id_avaliacao;

    IF NOT EXISTS (
        SELECT 1
          FROM registro
         WHERE id_usuario = v_usuario
           AND id_episodio = NEW.id_episodio
    ) THEN
        RAISE EXCEPTION
            'RN18: o usuário % não possui registro de exibição do episódio %',
            v_usuario, NEW.id_episodio;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_avaliacao_exige_registro
BEFORE INSERT ON avaliacao_episodio
FOR EACH ROW
EXECUTE FUNCTION fn_avaliacao_exige_registro();

-- ---------------------------------------------------------
-- Trigger 2 - RN19 + disjunção da especialização
-- Garante no máximo uma avaliação do mesmo usuário para o mesmo alvo
-- e impede que a mesma avaliação seja inserida em duas subclasses.
-- A regra compara dados distribuídos entre avaliacao e a subclasse.
-- ---------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_avaliacao_unica_por_alvo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_usuario INTEGER;
    v_tipo    VARCHAR(10);
    v_count   INTEGER;
BEGIN
    SELECT id_usuario, tipo_alvo
      INTO v_usuario, v_tipo
      FROM avaliacao
     WHERE id_avaliacao = NEW.id_avaliacao;

    IF v_tipo <> TG_TABLE_NAME
       AND NOT (
            (TG_TABLE_NAME = 'avaliacao_serie' AND v_tipo = 'serie')
         OR (TG_TABLE_NAME = 'avaliacao_temporada' AND v_tipo = 'temporada')
         OR (TG_TABLE_NAME = 'avaliacao_episodio' AND v_tipo = 'episodio')
       ) THEN
        RAISE EXCEPTION
            'Tipo de alvo incompatível: avaliação % foi criada como %, mas está sendo ligada a %',
            NEW.id_avaliacao, v_tipo, TG_TABLE_NAME;
    END IF;

    -- Disjunção: uma avaliação só pode pertencer a uma das três subclasses.
    SELECT COUNT(*)
      INTO v_count
      FROM (
            SELECT id_avaliacao FROM avaliacao_serie
             WHERE id_avaliacao = NEW.id_avaliacao
            UNION ALL
            SELECT id_avaliacao FROM avaliacao_temporada
             WHERE id_avaliacao = NEW.id_avaliacao
            UNION ALL
            SELECT id_avaliacao FROM avaliacao_episodio
             WHERE id_avaliacao = NEW.id_avaliacao
      ) AS subtipos;

    IF v_count > 0 THEN
        RAISE EXCEPTION
            'A avaliação % já está associada a uma subclasse de alvo',
            NEW.id_avaliacao;
    END IF;

    -- Unicidade usuário + alvo.
    IF TG_TABLE_NAME = 'avaliacao_serie' THEN
        IF EXISTS (
            SELECT 1
              FROM avaliacao a
              JOIN avaliacao_serie avs
                ON avs.id_avaliacao = a.id_avaliacao
             WHERE a.id_usuario = v_usuario
               AND avs.id_serie = NEW.id_serie
        ) THEN
            RAISE EXCEPTION
                'RN19: o usuário % já possui avaliação para a série %',
                v_usuario, NEW.id_serie;
        END IF;

    ELSIF TG_TABLE_NAME = 'avaliacao_temporada' THEN
        IF EXISTS (
            SELECT 1
              FROM avaliacao a
              JOIN avaliacao_temporada avt
                ON avt.id_avaliacao = a.id_avaliacao
             WHERE a.id_usuario = v_usuario
               AND avt.id_temporada = NEW.id_temporada
        ) THEN
            RAISE EXCEPTION
                'RN19: o usuário % já possui avaliação para a temporada %',
                v_usuario, NEW.id_temporada;
        END IF;

    ELSIF TG_TABLE_NAME = 'avaliacao_episodio' THEN
        IF EXISTS (
            SELECT 1
              FROM avaliacao a
              JOIN avaliacao_episodio ave
                ON ave.id_avaliacao = a.id_avaliacao
             WHERE a.id_usuario = v_usuario
               AND ave.id_episodio = NEW.id_episodio
        ) THEN
            RAISE EXCEPTION
                'RN19: o usuário % já possui avaliação para o episódio %',
                v_usuario, NEW.id_episodio;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_avaliacao_unica_por_alvo
BEFORE INSERT ON avaliacao_serie
FOR EACH ROW
EXECUTE FUNCTION fn_avaliacao_unica_por_alvo();

CREATE TRIGGER trg_avaliacao_unica_por_alvo_temporada
BEFORE INSERT ON avaliacao_temporada
FOR EACH ROW
EXECUTE FUNCTION fn_avaliacao_unica_por_alvo();

CREATE TRIGGER trg_avaliacao_unica_por_alvo_episodio
BEFORE INSERT ON avaliacao_episodio
FOR EACH ROW
EXECUTE FUNCTION fn_avaliacao_unica_por_alvo();

-- ---------------------------------------------------------
-- Trigger 3 - RN22
-- Impede que o autor da avaliação curta a própria avaliação.
-- ---------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_bloqueia_autocurtida()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_autor INTEGER;
BEGIN
    SELECT id_usuario
      INTO v_autor
      FROM avaliacao
     WHERE id_avaliacao = NEW.id_avaliacao;

    IF v_autor = NEW.id_usuario THEN
        RAISE EXCEPTION
            'RN22: o usuário % não pode curtir a própria avaliação %',
            NEW.id_usuario, NEW.id_avaliacao;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_bloqueia_autocurtida
BEFORE INSERT ON curtida
FOR EACH ROW
EXECUTE FUNCTION fn_bloqueia_autocurtida();

-- ---------------------------------------------------------
-- Trigger 4 - atributo derivado total_curtidas
-- Depois de inserir/remover uma curtida, recalcula a quantidade real.
-- ---------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_atualiza_contador_curtidas()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_id_avaliacao INTEGER;
BEGIN
    v_id_avaliacao := COALESCE(NEW.id_avaliacao, OLD.id_avaliacao);

    UPDATE avaliacao
       SET total_curtidas = (
           SELECT COUNT(*)
             FROM curtida
            WHERE id_avaliacao = v_id_avaliacao
       )
     WHERE id_avaliacao = v_id_avaliacao;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_atualiza_contador_curtidas
AFTER INSERT OR DELETE ON curtida
FOR EACH ROW
EXECUTE FUNCTION fn_atualiza_contador_curtidas();

-- ---------------------------------------------------------
-- Trigger 5 - RN14
-- Ao registrar um episódio, obtém a série correspondente e cria
-- ou promove o estado do usuário para 'assistindo'.
-- ---------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_garante_estado_assistindo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_serie INTEGER;
BEGIN
    SELECT t.id_serie
      INTO v_serie
      FROM episodio e
      JOIN temporada t
        ON t.id_temporada = e.id_temporada
     WHERE e.id_episodio = NEW.id_episodio;

    INSERT INTO estado_serie (id_usuario, id_serie, estado, data_atualizacao)
    VALUES (NEW.id_usuario, v_serie, 'assistindo', CURRENT_DATE)
    ON CONFLICT (id_usuario, id_serie)
    DO UPDATE SET
        estado = 'assistindo',
        data_atualizacao = CURRENT_DATE;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_garante_estado_assistindo
