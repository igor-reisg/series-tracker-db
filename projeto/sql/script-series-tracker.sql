-- =========================================================
-- 2. DDL - CRIAÇÃO DAS TABELAS
-- =========================================================

-- ---------------------------------------------------------
-- 2.1 Usuários
-- RN01: username e email são únicos; username segue o padrão
--       letras minúsculas, dígitos e sublinhado, de 3 a 30 chars.
-- ---------------------------------------------------------
CREATE TABLE usuario (
    id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    username       VARCHAR(30)  NOT NULL,
    email          VARCHAR(120) NOT NULL,
    nome_exibicao   VARCHAR(60),
    bio             TEXT,
    data_cadastro   DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_username
        CHECK (username ~ '^[a-z0-9_]{3,30}$')
);

-- ---------------------------------------------------------
-- 2.2 Relação social de seguidores
-- RN02: seguir é unidirecional.
-- RN03: um usuário não pode seguir a si mesmo.
-- RN04: exclusão de usuário remove seus relacionamentos sociais.
-- ---------------------------------------------------------
CREATE TABLE segue (
    id_seguidor INTEGER NOT NULL,
    id_seguido  INTEGER NOT NULL,
    data_inicio DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_segue PRIMARY KEY (id_seguidor, id_seguido),
    CONSTRAINT fk_segue_seguidor
        FOREIGN KEY (id_seguidor)
        REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_segue_seguido
        FOREIGN KEY (id_seguido)
        REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT ck_segue_nao_auto
        CHECK (id_seguidor <> id_seguido)
);

-- ---------------------------------------------------------
-- 2.3 Séries
-- ---------------------------------------------------------
CREATE TABLE serie (
    id_serie       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    titulo         VARCHAR(150) NOT NULL,
    titulo_original VARCHAR(150),
    sinopse        TEXT,
    ano_estreia    INTEGER,
    situacao       VARCHAR(15) NOT NULL,
    pais_origem    VARCHAR(2),

    CONSTRAINT pk_serie PRIMARY KEY (id_serie),
    CONSTRAINT ck_serie_situacao
        CHECK (situacao IN ('em_exibicao', 'encerrada', 'cancelada')),
    CONSTRAINT ck_serie_pais
        CHECK (pais_origem IS NULL OR char_length(pais_origem) = 2)
);

-- ---------------------------------------------------------
-- 2.4 Temporadas - entidade fraca
-- RN06: toda temporada pertence a uma série; número único
--       dentro da série.
-- RN08: dependência existencial em relação à série.
-- ---------------------------------------------------------
CREATE TABLE temporada (
    id_temporada INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_serie     INTEGER NOT NULL,
    numero       INTEGER NOT NULL,
    titulo       VARCHAR(100),
    data_estreia DATE,

    CONSTRAINT pk_temporada PRIMARY KEY (id_temporada),
    CONSTRAINT uk_temporada_serie_numero UNIQUE (id_serie, numero),
    CONSTRAINT fk_temporada_serie
        FOREIGN KEY (id_serie)
        REFERENCES serie (id_serie)
        ON DELETE CASCADE,
    CONSTRAINT ck_temporada_numero
        CHECK (numero > 0)
);

-- ---------------------------------------------------------
-- 2.5 Episódios - entidade fraca
-- RN07: toda episódio pertence a uma temporada; número único
--       dentro da temporada.
-- RN08: dependência existencial em relação à série/temporada.
-- ---------------------------------------------------------
CREATE TABLE episodio (
    id_episodio   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_temporada  INTEGER NOT NULL,
    numero        INTEGER NOT NULL,
    titulo        VARCHAR(150) NOT NULL,
    duracao_min   INTEGER,
    data_exibicao DATE,
    sinopse       TEXT,

    CONSTRAINT pk_episodio PRIMARY KEY (id_episodio),
    CONSTRAINT uk_episodio_temporada_numero UNIQUE (id_temporada, numero),
    CONSTRAINT fk_episodio_temporada
        FOREIGN KEY (id_temporada)
        REFERENCES temporada (id_temporada)
        ON DELETE CASCADE,
    CONSTRAINT ck_episodio_numero
        CHECK (numero > 0),
    CONSTRAINT ck_episodio_duracao
        CHECK (duracao_min IS NULL OR duracao_min > 0),
    -- RN12: não é permitido registrar episódio com data original futura.
    CONSTRAINT ck_episodio_data_exibicao
        CHECK (data_exibicao IS NULL OR data_exibicao <= CURRENT_DATE)
);

-- ---------------------------------------------------------
-- 2.6 Gêneros
-- RN05: nome do gênero é único.
-- A participação mínima de toda série em serie_genero (>= 1)
-- não é exprimível apenas por NOT NULL/UNIQUE/FK; a carga e a
-- camada de aplicação garantem que nenhuma série fique sem gênero.
-- ---------------------------------------------------------
CREATE TABLE genero (
    id_genero INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome      VARCHAR(40) NOT NULL,

    CONSTRAINT pk_genero PRIMARY KEY (id_genero),
    CONSTRAINT uk_genero_nome UNIQUE (nome)
);

-- ---------------------------------------------------------
-- 2.7 Classificação série-gênero
-- RN05: relacionamento N:N.
-- ---------------------------------------------------------
CREATE TABLE serie_genero (
    id_serie  INTEGER NOT NULL,
    id_genero INTEGER NOT NULL,

    CONSTRAINT pk_serie_genero PRIMARY KEY (id_serie, id_genero),
    CONSTRAINT fk_serie_genero_serie
        FOREIGN KEY (id_serie)
        REFERENCES serie (id_serie)
        ON DELETE CASCADE,
    CONSTRAINT fk_serie_genero_genero
        FOREIGN KEY (id_genero)
        REFERENCES genero (id_genero)
        ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 2.8 Pessoas do meio audiovisual
-- ---------------------------------------------------------
CREATE TABLE pessoa (
    id_pessoa       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(120) NOT NULL,
    data_nascimento DATE,
    nacionalidade   VARCHAR(60),

    CONSTRAINT pk_pessoa PRIMARY KEY (id_pessoa)
);

-- ---------------------------------------------------------
-- 2.9 Participações
-- RN09: uma pessoa pode exercer mais de uma função na mesma série.
-- RN10: personagem só existe para a função ator.
-- ---------------------------------------------------------
CREATE TABLE participacao (
    id_pessoa  INTEGER NOT NULL,
    id_serie   INTEGER NOT NULL,
    funcao     VARCHAR(20) NOT NULL,
    personagem VARCHAR(120),

    CONSTRAINT pk_participacao PRIMARY KEY (id_pessoa, id_serie, funcao),
    CONSTRAINT fk_participacao_pessoa
        FOREIGN KEY (id_pessoa)
        REFERENCES pessoa (id_pessoa)
        ON DELETE CASCADE,
    CONSTRAINT fk_participacao_serie
        FOREIGN KEY (id_serie)
        REFERENCES serie (id_serie)
        ON DELETE CASCADE,
    CONSTRAINT ck_participacao_funcao
        CHECK (funcao IN ('ator', 'diretor', 'roteirista', 'criador')),
    CONSTRAINT ck_participacao_personagem
        CHECK (
            (funcao = 'ator' AND personagem IS NOT NULL)
            OR
            (funcao <> 'ator' AND personagem IS NULL)
        )
);

-- ---------------------------------------------------------
-- 2.10 Estado declarado da série
-- RN13: no máximo um estado por usuário e série (PK composta).
-- RN14: registros de exibição promovem o estado para assistindo;
--       o gatilho correspondente é criado posteriormente.
-- ---------------------------------------------------------
CREATE TABLE estado_serie (
    id_usuario       INTEGER NOT NULL,
    id_serie         INTEGER NOT NULL,
    estado           VARCHAR(15) NOT NULL,
    data_atualizacao DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_estado_serie PRIMARY KEY (id_usuario, id_serie),
    CONSTRAINT fk_estado_serie_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_estado_serie_serie
        FOREIGN KEY (id_serie)
        REFERENCES serie (id_serie)
        ON DELETE RESTRICT,
    CONSTRAINT ck_estado_serie_estado
        CHECK (estado IN ('watchlist', 'assistindo', 'abandonada'))
);

-- ---------------------------------------------------------
-- 2.11 Histórico de exibição
-- RN11: o mesmo episódio pode ser registrado várias vezes,
--       desde que a data do evento seja diferente.
-- RN12: data_assistido não pode ser futura.
-- RN14: AFTER INSERT promove a série a assistindo.
-- ---------------------------------------------------------
CREATE TABLE registro (
    id_registro   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    INTEGER NOT NULL,
    id_episodio   INTEGER NOT NULL,
    data_assistido DATE NOT NULL,

    CONSTRAINT pk_registro PRIMARY KEY (id_registro),
    CONSTRAINT uk_registro_evento UNIQUE
        (id_usuario, id_episodio, data_assistido),
    CONSTRAINT fk_registro_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_registro_episodio
        FOREIGN KEY (id_episodio)
        REFERENCES episodio (id_episodio)
        ON DELETE RESTRICT,
    CONSTRAINT ck_registro_data
        CHECK (data_assistido <= CURRENT_DATE)
);

-- ---------------------------------------------------------
-- 2.12 Avaliação - superclasse
-- RN15: avaliação pertence a um usuário e possui um tipo de alvo.
-- RN16: nota entre 0,5 e 5,0, em incrementos de 0,5.
-- RN17: nota ou texto é obrigatório.
-- RN20: contem_spoiler sinaliza spoiler.
-- total_curtidas é atributo derivado materializado; o gatilho de
-- sincronização é criado posteriormente.
-- ---------------------------------------------------------
CREATE TABLE avaliacao (
    id_avaliacao    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario      INTEGER NOT NULL,
    nota            NUMERIC(2,1),
    texto           TEXT,
    contem_spoiler  BOOLEAN NOT NULL DEFAULT FALSE,
    data_publicacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_alvo       VARCHAR(10) NOT NULL,
    total_curtidas  INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT pk_avaliacao PRIMARY KEY (id_avaliacao),
    CONSTRAINT fk_avaliacao_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT ck_avaliacao_nota
        CHECK (
            nota IS NULL
            OR (
                nota >= 0.5
                AND nota <= 5.0
                AND MOD(nota * 10, 5) = 0
            )
        ),
    CONSTRAINT ck_avaliacao_nao_vazia
        CHECK (nota IS NOT NULL OR texto IS NOT NULL),
    CONSTRAINT ck_avaliacao_tipo_alvo
        CHECK (tipo_alvo IN ('serie', 'temporada', 'episodio')),
    CONSTRAINT ck_avaliacao_total_curtidas
        CHECK (total_curtidas >= 0)
);

-- ---------------------------------------------------------
-- 2.13-2.15 Especialização da avaliação
-- Estratégia (b): superclasse + uma relação por subclasse.
-- A PK da subclasse também é FK para avaliacao.
-- RN18 é garantida por trigger na avaliação de episódio.
-- RN19/disjunção são reforçadas pelos gatilhos das subclasses.
-- A totalidade da especialização é garantida pelo processo de
-- inserção: avaliação + uma subclasse devem ser criadas na mesma
-- transação.
-- ---------------------------------------------------------
CREATE TABLE avaliacao_serie (
    id_avaliacao INTEGER NOT NULL,
    id_serie     INTEGER NOT NULL,

    CONSTRAINT pk_avaliacao_serie PRIMARY KEY (id_avaliacao),
    CONSTRAINT fk_avaliacao_serie_avaliacao
        FOREIGN KEY (id_avaliacao)
        REFERENCES avaliacao (id_avaliacao)
        ON DELETE CASCADE,
    CONSTRAINT fk_avaliacao_serie_serie
        FOREIGN KEY (id_serie)
        REFERENCES serie (id_serie)
        ON DELETE RESTRICT
);

CREATE TABLE avaliacao_temporada (
    id_avaliacao INTEGER NOT NULL,
    id_temporada INTEGER NOT NULL,

    CONSTRAINT pk_avaliacao_temporada PRIMARY KEY (id_avaliacao),
    CONSTRAINT fk_avaliacao_temporada_avaliacao
        FOREIGN KEY (id_avaliacao)
        REFERENCES avaliacao (id_avaliacao)
        ON DELETE CASCADE,
    CONSTRAINT fk_avaliacao_temporada_temporada
        FOREIGN KEY (id_temporada)
        REFERENCES temporada (id_temporada)
        ON DELETE RESTRICT
);

CREATE TABLE avaliacao_episodio (
    id_avaliacao INTEGER NOT NULL,
    id_episodio  INTEGER NOT NULL,

    CONSTRAINT pk_avaliacao_episodio PRIMARY KEY (id_avaliacao),
    CONSTRAINT fk_avaliacao_episodio_avaliacao
        FOREIGN KEY (id_avaliacao)
        REFERENCES avaliacao (id_avaliacao)
        ON DELETE CASCADE,
    CONSTRAINT fk_avaliacao_episodio_episodio
        FOREIGN KEY (id_episodio)
        REFERENCES episodio (id_episodio)
        ON DELETE RESTRICT
);

-- ---------------------------------------------------------
-- 2.16 Curtidas
-- RN21: uma curtida por usuário e avaliação (PK composta).
-- RN22: ninguém pode curtir a própria avaliação; trigger abaixo.
-- RN24: exclusão de avaliação exclui suas curtidas.
-- ---------------------------------------------------------
CREATE TABLE curtida (
    id_usuario    INTEGER NOT NULL,
    id_avaliacao  INTEGER NOT NULL,
    data_curtida  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_curtida PRIMARY KEY (id_usuario, id_avaliacao),
    CONSTRAINT fk_curtida_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_curtida_avaliacao
        FOREIGN KEY (id_avaliacao)
        REFERENCES avaliacao (id_avaliacao)
        ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 2.17 Comentários
-- RN23: resposta opcional a outro comentário da mesma avaliação.
-- O FK composto (id_comentario_pai, id_avaliacao) garante que o pai
