        FOREIGN KEY (id_comentario_pai, id_avaliacao)
        REFERENCES comentario (id_comentario, id_avaliacao)
        ON DELETE CASCADE,
    CONSTRAINT ck_comentario_nao_vazio
        CHECK (btrim(texto) <> '')
);

