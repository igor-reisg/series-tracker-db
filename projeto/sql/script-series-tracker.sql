-- ---------------------------------------------------------
-- Consulta 1 - Ranking de séries por nota média
-- Pergunta: quais séries possuem as melhores avaliações, considerando
-- apenas as que receberam número significativo de notas?
-- Conteúdo exercitado: JOIN, AVG, COUNT, GROUP BY, HAVING, ORDER BY.
-- O HAVING >= 3 evita que uma única nota alta domine o ranking.
-- ---------------------------------------------------------
SELECT
    id_serie,
    titulo_alvo AS serie,
    ROUND(AVG(nota), 2) AS nota_media,
    COUNT(*) AS quantidade_notas
FROM vw_avaliacao_completa
WHERE tipo_alvo = 'serie'
  AND nota IS NOT NULL
GROUP BY id_serie, titulo_alvo
HAVING COUNT(*) >= 3
ORDER BY nota_media DESC, quantidade_notas DESC, serie;

-- ---------------------------------------------------------
-- Consulta 2 - Atividade recente de quem o usuário segue
-- Pergunta: quais foram as últimas avaliações publicadas pelos usuários
-- que o usuário 1 segue?
-- Conteúdo exercitado: subconsulta IN, auto-relacionamento segue e visão.
-- ---------------------------------------------------------
SELECT
    username,
    tipo_alvo,
    titulo_alvo,
    nota,
    data_publicacao
FROM vw_avaliacao_completa
WHERE id_usuario IN (
    SELECT id_seguido
    FROM segue
    WHERE id_seguidor = 1
)
ORDER BY data_publicacao DESC
LIMIT 10;

-- Formulação equivalente usando EXISTS:
SELECT
    v.username,
    v.tipo_alvo,
    v.titulo_alvo,
    v.nota,
    v.data_publicacao
FROM vw_avaliacao_completa v
WHERE EXISTS (
    SELECT 1
    FROM segue sg
    WHERE sg.id_seguidor = 1
      AND sg.id_seguido = v.id_usuario
)
ORDER BY v.data_publicacao DESC
LIMIT 10;

-- ---------------------------------------------------------
-- Consulta 3 - Séries na lista de interesse ainda não iniciadas
-- Pergunta: quais séries o usuário 1 marcou como 'watchlist' sem
-- ter assistido a nenhum episódio?
-- Conteúdo exercitado: operação de conjunto EXCEPT.
-- ---------------------------------------------------------
SELECT
    s.id_serie,
    s.titulo
FROM estado_serie es
JOIN serie s
  ON s.id_serie = es.id_serie
WHERE es.id_usuario = 2
  AND es.estado = 'watchlist'

EXCEPT

SELECT DISTINCT
    s.id_serie,
    s.titulo
FROM estado_serie es
JOIN serie s
  ON s.id_serie = es.id_serie
JOIN temporada t
  ON t.id_serie = s.id_serie
JOIN episodio e
  ON e.id_temporada = t.id_temporada
JOIN registro r
  ON r.id_episodio = e.id_episodio
 AND r.id_usuario = es.id_usuario
WHERE es.id_usuario = 1;

-- Formulação equivalente usando NOT EXISTS:
SELECT
    s.id_serie,
    s.titulo
FROM estado_serie es
JOIN serie s
  ON s.id_serie = es.id_serie
WHERE es.id_usuario = 2
  AND es.estado = 'watchlist'
  AND NOT EXISTS (
      SELECT 1
      FROM temporada t
      JOIN episodio e
        ON e.id_temporada = t.id_temporada
      JOIN registro r
        ON r.id_episodio = e.id_episodio
       AND r.id_usuario = es.id_usuario
      WHERE t.id_serie = s.id_serie
  );

