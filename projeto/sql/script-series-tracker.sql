-- ---------------------------------------------------------
-- 4.1 Visão unificada das avaliações
-- UNION ALL recompõe, para leitura, a fragmentação criada pela
-- especialização da entidade avaliacao.
-- ---------------------------------------------------------
CREATE OR REPLACE VIEW vw_avaliacao_completa AS
SELECT
    a.id_avaliacao,
    a.id_usuario,
    u.username,
    a.nota,
    a.texto,
    a.contem_spoiler,
    a.data_publicacao,
    a.tipo_alvo,
    a.total_curtidas,
    s.id_serie,
    NULL::INTEGER AS id_temporada,
    NULL::INTEGER AS id_episodio,
    s.titulo AS titulo_alvo
FROM avaliacao a
JOIN usuario u
  ON u.id_usuario = a.id_usuario
JOIN avaliacao_serie avs
  ON avs.id_avaliacao = a.id_avaliacao
JOIN serie s
  ON s.id_serie = avs.id_serie

UNION ALL

SELECT
    a.id_avaliacao,
    a.id_usuario,
    u.username,
    a.nota,
    a.texto,
    a.contem_spoiler,
    a.data_publicacao,
    a.tipo_alvo,
    a.total_curtidas,
    s.id_serie,
    t.id_temporada,
    NULL::INTEGER AS id_episodio,
    s.titulo || ' - Temporada ' || t.numero::TEXT
        || CASE
               WHEN t.titulo IS NOT NULL THEN ' (' || t.titulo || ')'
               ELSE ''
           END AS titulo_alvo
FROM avaliacao a
JOIN usuario u
  ON u.id_usuario = a.id_usuario
JOIN avaliacao_temporada avt
  ON avt.id_avaliacao = a.id_avaliacao
JOIN temporada t
  ON t.id_temporada = avt.id_temporada
JOIN serie s
  ON s.id_serie = t.id_serie

UNION ALL

SELECT
    a.id_avaliacao,
    a.id_usuario,
    u.username,
    a.nota,
    a.texto,
    a.contem_spoiler,
    a.data_publicacao,
    a.tipo_alvo,
    a.total_curtidas,
    s.id_serie,
    t.id_temporada,
    e.id_episodio,
    s.titulo || ' - T' || t.numero::TEXT
        || 'E' || e.numero::TEXT
        || ': ' || e.titulo AS titulo_alvo
FROM avaliacao a
JOIN usuario u
  ON u.id_usuario = a.id_usuario
JOIN avaliacao_episodio ave
  ON ave.id_avaliacao = a.id_avaliacao
JOIN episodio e
  ON e.id_episodio = ave.id_episodio
JOIN temporada t
  ON t.id_temporada = e.id_temporada
JOIN serie s
  ON s.id_serie = t.id_serie;

-- ---------------------------------------------------------
-- 4.2 Progresso por usuário e série
-- RN11 exige COUNT(DISTINCT id_episodio), pois reexibições não
-- podem aumentar artificialmente o percentual de progresso.
-- ---------------------------------------------------------
CREATE OR REPLACE VIEW vw_progresso_serie AS
SELECT
    es.id_usuario,
    es.id_serie,
    s.titulo,
    es.estado,
    COUNT(DISTINCT r.id_episodio) AS episodios_assistidos,
    COUNT(DISTINCT e.id_episodio) AS total_episodios,
    ROUND(
        100.0 * COUNT(DISTINCT r.id_episodio)
        / NULLIF(COUNT(DISTINCT e.id_episodio), 0),
        2
    ) AS percentual_progresso
FROM estado_serie es
JOIN serie s
  ON s.id_serie = es.id_serie
JOIN temporada t
  ON t.id_serie = es.id_serie
JOIN episodio e
  ON e.id_temporada = t.id_temporada
LEFT JOIN registro r
  ON r.id_usuario = es.id_usuario
 AND r.id_episodio = e.id_episodio
GROUP BY
    es.id_usuario,
    es.id_serie,
    s.titulo,
    es.estado;

